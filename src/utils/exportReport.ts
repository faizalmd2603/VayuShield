import type { AggregateImpactResult } from '../domain/impactCalculator';
import type { CombinedAirTelemetry } from '../types/airQuality';
import type { VayuShieldPlan } from '../types/gemini';

/**
 * Generates an executive Markdown report of the VayuShield action plan.
 *
 * @param plan Generated Gemini action plan
 * @param telemetry Live air quality telemetry
 * @param impact Calculated choice impact metrics
 * @returns Markdown string suitable for downloading or sharing
 */
export function generateMarkdownReport(
  plan: VayuShieldPlan,
  telemetry: CombinedAirTelemetry,
  impact: AggregateImpactResult
): string {
  const dateStr = new Date(plan.generatedAt).toLocaleString();

  return `# 🛡️ VayuShield Winter Smog Action Report
**Generated:** ${dateStr}
**Location:** ${telemetry.location.name}, ${telemetry.location.country}
**Current Air Quality:** CPCB NAQI ${telemetry.cpcbAqi.aqi} (${telemetry.cpcbAqi.category}) | GRAP ${telemetry.grapStage}
**Dominant Pollutant:** ${telemetry.cpcbAqi.dominantPollutant} (${telemetry.currentPollutants.pm25} µg/m³)
**Thermal Inversion Risk:** ${telemetry.smogTrap.riskLevel}

---

## 📊 Quantified Choice Impact Summary
- **Personal PM2.5 Inhalation Reduced:** ${impact.personalPm25ReductionUgm3} µg/m³
- **Weekly Household CO₂e Avoided:** ${impact.weeklyCo2eAvoidedKg} kg
- **Neighborhood PM2.5 Prevented:** ${impact.communityPmPreventedGrams} grams
- **Equivalent Tree Absorption:** ~${impact.treeAbsorptionEquivalent} trees/week

---

## 📋 Executive Advisory
${plan.summaryAdvisory}

---

## 🕒 24-Hour Low-Emission Routine Timeline
${plan.routines
  .map(
    (r) => `### ${r.timeSlot} — ${r.periodLabel}
- **Action:** ${r.action}
- **Meteorological Rationale:** ${r.whyNow}
- **Low-Emission Alternative:** ${r.lowEmissionAlternative}
- **Quantified Direct Impact:** -${r.directImpact.personalPm25ReductionUgm3} µg/m³ PM2.5, -${r.directImpact.co2eAvoidedKg} kg CO₂e (${r.directImpact.healthBenefit})
`
  )
  .join('\n')}

---

## 💡 Indoor Air Quality Hacks & Sustainable Swaps
${plan.indoorHacks
  .map(
    (h) => `### [${h.category}] ${h.title} (Effort: ${h.effortLevel} | Cost: ${h.estimatedCost})
- **Description:** ${h.description}
- **Direct Health Impact:** ${h.directHealthImpact}
- **Ventilation / CADR Delta:** ${h.achCadrImprovement}
`
  )
  .join('\n')}

---

## 📢 Community & Neighborhood Playbook
**Audience:** ${plan.communityPlaybook.targetAudience}
**Context:** ${plan.communityPlaybook.currentGrapContext}

### Action Checklist:
${plan.communityPlaybook.actionChecklist.map((item) => `- [ ] ${item}`).join('\n')}

### Noticeboard / WhatsApp Advisory Notice:
\`\`\`text
${plan.communityPlaybook.advisoryNoticeText}
\`\`\`

*Report generated by VayuShield — Production GenAI Urban Smog Assistant.*
`;
}
